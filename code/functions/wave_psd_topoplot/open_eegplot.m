function open_eegplot(EEG, subject, session, condition)

% =========================================================
% EEG波形をeegplotで表示する
%
% さらにeegplot上に
% ・PSD Channel選択
% ・PSD表示ボタン
% ・Band選択
% ・Topoplot表示ボタン
% を追加する
%
% Input
%   EEG       : EEGLAB EEG構造体
%   subject   : "sub-001"など
%   session   : "pre" / "post"
%   condition : "slMedita"など
% =========================================================


%% =========================================================
% eegplot
% ==========================================================

% 他のeegplotと区別するTag
eegplot_tag = ...
    "L_FAME_EEGPLOT_" + ...
    subject + "_" + ...
    session + "_" + ...
    condition;


eegplot( ...
    EEG.data, ...
    'srate', EEG.srate, ...
    'eloc_file', EEG.chanlocs, ...
    'events', EEG.event, ...
    'dispchans', 20, ...
    'winlength', 4.096, ...
    'tag', char(eegplot_tag), ...
    'title', char( ...
        subject + ...
        " / " + ...
        session + ...
        " / " + ...
        condition + ...
        " [ICA removed]"));


% Figure生成を待つ
drawnow;


%% =========================================================
% eegplot Figureを取得
% ==========================================================

eegFigs = findall( ...
    groot, ...
    'Type', 'figure', ...
    'Tag', char(eegplot_tag));


if isempty(eegFigs)

    warning("eegplot Figureを取得できませんでした");

    return;

end


eegFig = eegFigs(1);


if ~isgraphics(eegFig, 'figure')

    warning("取得したオブジェクトがFigureではありません");

    return;

end


%% =========================================================
% Channel一覧
% ==========================================================

channel_labels = string({EEG.chanlocs.labels});


%% =========================================================
% PSD Channel ラベル
% ==========================================================

uicontrol( ...
    'Parent', eegFig, ...
    'Style', 'text', ...
    'Units', 'normalized', ...
    'Position', [0.80 0.91 0.08 0.035], ...
    'String', 'PSD Channel', ...
    'HorizontalAlignment', 'center');


%% =========================================================
% PSD Channel 選択
% ==========================================================

psdChannelMenu = uicontrol( ...
    'Parent', eegFig, ...
    'Style', 'popupmenu', ...
    'Units', 'normalized', ...
    'Position', [0.88 0.91 0.07 0.04], ...
    'String', cellstr(channel_labels));


% Fzを初期値にする
fz_idx = find( ...
    strcmpi(channel_labels, "Fz"), ...
    1);


if ~isempty(fz_idx)

    psdChannelMenu.Value = fz_idx;

end


%% =========================================================
% PSD ボタン
% ==========================================================

uicontrol( ...
    'Parent', eegFig, ...
    'Style', 'pushbutton', ...
    'Units', 'normalized', ...
    'Position', [0.88 0.86 0.07 0.045], ...
    'String', 'PSD', ...
    'FontWeight', 'bold', ...
    'Callback', @(~, ~) plot_current_psd( ...
        EEG, ...
        eegFig, ...
        psdChannelMenu, ...
        subject, ...
        session, ...
        condition));


%% =========================================================
% Band ラベル
% ==========================================================

uicontrol( ...
    'Parent', eegFig, ...
    'Style', 'text', ...
    'Units', 'normalized', ...
    'Position', [0.81 0.81 0.07 0.035], ...
    'String', 'Band', ...
    'HorizontalAlignment', 'center');


%% =========================================================
% Band 選択
% ==========================================================

bandMenu = uicontrol( ...
    'Parent', eegFig, ...
    'Style', 'popupmenu', ...
    'Units', 'normalized', ...
    'Position', [0.88 0.81 0.07 0.04], ...
    'String', { ...
        'Delta', ...
        'Theta', ...
        'Alpha', ...
        'Beta', ...
        'Gamma'}, ...
    'Value', 3);


%% =========================================================
% Topoplot ボタン
% ==========================================================

uicontrol( ...
    'Parent', eegFig, ...
    'Style', 'pushbutton', ...
    'Units', 'normalized', ...
    'Position', [0.88 0.76 0.07 0.045], ...
    'String', 'Topoplot', ...
    'FontWeight', 'bold', ...
    'Callback', @(~, ~) plot_current_topoplot( ...
        EEG, ...
        eegFig, ...
        bandMenu, ...
        subject, ...
        session, ...
        condition));

end